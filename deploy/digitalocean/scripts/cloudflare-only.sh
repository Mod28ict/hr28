#!/usr/bin/env bash
# Web ports (80/443) accept Cloudflare only, so nobody can go around Cloudflare's WAF by using
# the droplet's IP. Also refreshes Nginx's list of Cloudflare addresses (real visitor IP).
# Safe to re-run: adds new Cloudflare ranges and removes ones Cloudflare no longer uses.
# Installed as /usr/local/sbin/hr28-cloudflare-only; run as root (monthly by cron).
set -euo pipefail
[ "$(id -u)" -eq 0 ] || { echo "Run as root."; exit 1; }

TAG=hr28-cloudflare
SNIPPET=/etc/nginx/snippets/hr28-cloudflare-real-ip.conf
TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT

curl -fsS --max-time 20 https://www.cloudflare.com/ips-v4 -o "$TMP/v4"
curl -fsS --max-time 20 https://www.cloudflare.com/ips-v6 -o "$TMP/v6"
cat "$TMP/v4" "$TMP/v6" | tr -d '\r' | grep -E '^[0-9a-f:.]+/[0-9]+$' | sort -u > "$TMP/ranges"
# Never act on a broken download: Cloudflare has about 15 IPv4 and 7 IPv6 ranges.
[ "$(grep -c '\.' "$TMP/ranges")" -ge 10 ] && [ "$(grep -c ':' "$TMP/ranges")" -ge 5 ] \
    || { echo "Cloudflare's address list looks wrong; nothing changed."; exit 1; }

# 1. Firewall: allow every current range, then drop "anyone" and ranges no longer listed.
while read -r range; do
    ufw allow proto tcp from "$range" to any port 80,443 comment "$TAG" >/dev/null
done < "$TMP/ranges"
ufw show added | grep "comment '$TAG'" | sed -E 's/.* from ([^ ]+) .*/\1/' | sort -u > "$TMP/current"
comm -23 "$TMP/current" "$TMP/ranges" | while read -r old; do
    ufw delete allow proto tcp from "$old" to any port 80,443 >/dev/null
done
for rule in "80/tcp" "443/tcp" "80" "443" "Nginx Full" "Nginx HTTP" "Nginx HTTPS"; do
    ufw delete allow "$rule" >/dev/null 2>&1 || true
done

# 2. Nginx: trust the visitor address only from the same ranges.
{
    echo "# Generated by hr28-cloudflare-only from Cloudflare's published ranges. Do not edit."
    sed 's/^/set_real_ip_from /; s/$/;/' "$TMP/ranges"
    echo "real_ip_header CF-Connecting-IP;"
} > "$TMP/snippet"
if ! cmp -s "$TMP/snippet" "$SNIPPET"; then
    cp "$SNIPPET" "$TMP/snippet.old" 2>/dev/null || true
    install -m 644 "$TMP/snippet" "$SNIPPET"
    if nginx -t >/dev/null 2>&1; then systemctl reload nginx
    else [ -f "$TMP/snippet.old" ] && install -m 644 "$TMP/snippet.old" "$SNIPPET"; echo "Nginx rejected the new list; kept the old one."; exit 1
    fi
fi
echo "Web ports open to $(wc -l < "$TMP/ranges") Cloudflare ranges only."
